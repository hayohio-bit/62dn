/**
 * 합성 표기를 기본 털색으로 풀어 쓴다.
 * "황갈색·흑갈색·회갈색·연갈색"은 갈색 계열 한 가지이고, "흑백"은 흰색과 검정 두 가지다.
 * 한 글자 키워드(황·갈·흑)가 합성어 안에서 따로 세어져 삼색으로 잘못 분류되는 것을 막는다.
 */
function normalizeColorText(text) {
  return text.replace(/(황|흑|회|연|적|암)갈/g, "갈").replace(/흑백/g, "검정 흰색");
}

/** 문자열에 나온 기본 털색을 나온 순서대로 돌려준다 (중복 없음) */
function baseColors(text) {
  const found = [];
  for (const [tag, words] of Object.entries(COLOR_KEYWORDS)) {
    const idx = Math.min(...words.map((w) => text.indexOf(w)).map((i) => (i < 0 ? Infinity : i)));
    if (idx !== Infinity) found.push([idx, tag]);
  }
  return found.sort((a, b) => a[0] - b[0]).map(([, tag]) => tag);
}

/**
 * 공공데이터의 털색 문자열(colorCd)을 이름 후보 태그로 분류한다. 알 수 없으면 null.
 * 무늬(삼색·턱시도·고등어·얼룩)를 먼저 보고, 없으면 기본 털색 중 먼저 나온 것을 쓴다.
 * 흰색+검정이 섞인 경우 고양이는 턱시도, 개는 얼룩으로 본다.
 */
export function colorTag(color, isCat) {
  const text = normalizeColorText(String(color ?? "").trim());
  if (text === "") return null;
  if (text.includes("삼색") || text.includes("카오스")) return "tricolor";
  if (text.includes("턱시도")) return "tuxedo";
  if (["고등어", "태비", "줄무늬", "호랑", "브린들", "호피"].some((w) => text.includes(w))) return "tabby";
  if (["얼룩", "점박", "젖소", "바둑"].some((w) => text.includes(w))) return "spotted";
  const colors = baseColors(text);
  if (colors.length >= 3) return "tricolor";
  if (colors.length === 2 && colors.includes("white") && colors.includes("black")) return isCat ? "tuxedo" : "spotted";
  return colors[0] ?? null;
}

/** 1살 이하는 young, 8살 이상은 senior, 그 사이와 모르면 null */
export function ageGroup(age) {
  if (age == null) return null;
  if (age <= 1) return "young";
  if (age >= 8) return "senior";
  return null;
}

/** 품종 이름에 포함된 키워드로 품종 태그를 찾는다. 믹스처럼 특징이 없으면 null */
export function breedTag(breed) {
  const text = String(breed ?? "");
  for (const [tag, words] of BREED_KEYWORDS) {
    if (words.some((w) => text.includes(w))) return tag;
  }
  return null;
}

/**
 * 동물의 특징에 맞는 이름 후보를 모아 돌려준다. 알 수 있는 특징이 하나도 없으면 빈 배열이다.
 * 털색 풀은 COLOR_WEIGHT번 넣어 선택될 비중을 높인다.
 */
/** 털색 풀을 후보에 넣는 횟수. 털색은 가장 눈에 띄는 특징이라 크기·나이·품종보다 선택될 비중을 높인다 */
export const COLOR_WEIGHT = 3;

export function traitCandidates({ color, size, age, breed, isCat = false } = {}) {
  const tag = colorTag(color, isCat);
  // 고양이의 줄무늬(고등어·태비)는 생선 이름 풀을, 개의 호랑이 무늬는 브린들 풀을 쓴다
  const colorPool = COLOR_POOLS[tag === "tabby" && !isCat ? "brindle" : tag] ?? [];
  const breedPool = BREED_POOLS[breedTag(breed)] ?? [];
  // 크기는 개에게만 특징으로 본다 (고양이는 대부분 5kg 미만이라 구분이 되지 않고, 큰 값은 체중 오입력일 수 있다)
  const sizePool = isCat ? [] : (SIZE_POOLS[size] ?? []);
  const agePool = AGE_POOLS[ageGroup(age)] ?? [];
  return [...Array(COLOR_WEIGHT).fill(colorPool).flat(), ...breedPool, ...sizePool, ...agePool];
}

/**
 * 스냅샷의 털색 분류 현황. 규칙이 실제 데이터의 표기를 얼마나 알아보는지 게시 로그로 확인하는 데 쓴다.
 * 분류하지 못한 값은 많이 나온 순으로 돌려준다 (키가 아니라 공고의 털색 표기이므로 로그에 남겨도 된다).
 */
export function summarizeColors(animals, topUnclassified = 15) {
  const byTag = {};
  const unclassified = new Map();
  let missing = 0;
  for (const a of animals) {
    if (a.color == null || String(a.color).trim() === "") {
      missing += 1;
      continue;
    }
    const tag = colorTag(a.color, a.species === "CAT");
    if (tag) byTag[tag] = (byTag[tag] ?? 0) + 1;
    else unclassified.set(a.color, (unclassified.get(a.color) ?? 0) + 1);
  }
  const unclassifiedTotal = [...unclassified.values()].reduce((s, n) => s + n, 0);
  return {
    total: animals.length,
    missing,
    classified: Object.values(byTag).reduce((s, n) => s + n, 0),
    unclassified: unclassifiedTotal,
    byTag,
    topUnclassified: [...unclassified].sort((x, y) => y[1] - x[1]).slice(0, topUnclassified),
  };
}
